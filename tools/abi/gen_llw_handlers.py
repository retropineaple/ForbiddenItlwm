#!/usr/bin/env python3
"""Generate ForbiddenItlwm/AirportLLWHandlers.inc: one "unsupported" override for every pure virtual request
handler of IO80211InfraProtocol (macOS Sequoia header).

The low latency interface (llw0) sits on the same class chain as the Wi-Fi interface, so the compiler needs
all of that chain's request handlers. llw0 answers none of them: it only carries data.

  python3 tools/abi/gen_llw_handlers.py          # rewrites the .inc from the header
  python3 tools/abi/gen_llw_handlers.py --check  # exits 1 if the .inc is out of date
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
header = root / 'include/Airport/macOS15/IO80211InfraProtocol.h'
output = root / 'ForbiddenItlwm/AirportLLWHandlers.inc'

text = header.read_text()
body = text[text.index('class IO80211InfraProtocol'):]
handlers = re.findall(r'^\s*virtual IOReturn (\w+)\(([^)]*)\) = 0;', body, re.M)
if not handlers:
    sys.exit('no pure virtual handlers found in %s' % header)

lines = ['// Generated by tools/abi/gen_llw_handlers.py from include/Airport/macOS15/IO80211InfraProtocol.h.',
         '// %d request handlers, in the header\'s (virtual table) order. Do not edit by hand.' % len(handlers)]
lines += ['IOReturn %s(%s) override { return kIOReturnUnsupported; }' % (name, args) for name, args in handlers]
generated = '\n'.join(lines) + '\n'

if '--check' in sys.argv:
    sys.exit(0 if output.exists() and output.read_text() == generated else 1)
output.write_text(generated)
print('%s: %d handlers' % (output.relative_to(root), len(handlers)))
